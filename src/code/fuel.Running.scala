package fuel

import soundness.*

import pyrocosm.{Block, Inline}

object Running:
  // What a fragment wrote as it ran, as a terminal would show it — its text, and the styles of
  // its runs — and what it threw, if it threw.
  case class Outcome(text: Text, runs: List[Block.Run], error: Optional[Throwable])

// How a `run` fragment is run: its body, which loads the object it was compiled as, with what
// it writes captured. An embedding given none does not run its fragments, as a checker which
// does not compile does not check them.
trait Running:
  def run(body: => Unit): Running.Outcome

object Phrasing:
  // Markdown phrasing as the model converts it, with nothing linked.
  val markdown: Phrasing = new Phrasing:
    def inline(text: Text, linker: Linker): List[Inline] = pyrocosm.Markdowns.inline(text)

// How the Markdown of a label — a frame's, an alternative's — becomes phrasing, its references
// linked through the linker.
trait Phrasing:
  def inline(text: Text, linker: Linker): List[Inline]
