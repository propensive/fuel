package fuel

import java.util.concurrent as juc

import soundness.*

// The daemon's state: the corpus the latest `fuel compile` produced, from whichever shell, and
// an edition the dashboard watches so that it rebuilds only when a compile has happened.
object Server:
  @scala.caps.unsafe.untrackedCaptures
  @volatile
  private var corpus0: Optional[Corpus] = Unset

  private val edition0: juc.atomic.AtomicLong = juc.atomic.AtomicLong(0L)

  def publish(corpus: Corpus): Unit =
    corpus0 = corpus
    edition0.incrementAndGet()

  def corpus: Optional[Corpus] = corpus0
  def edition: Long = edition0.get
