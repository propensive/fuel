package fuel

import scala.quoted.Quotes

import dotty.tools.dotc.core.{Symbols, Types}

// The compiler's own types and symbols as the quotes API's. In the compiler's `QuotesImpl` the
// API's abstract `TypeRepr` and `Symbol` are exactly the compiler's `Type` and `Symbol`, but
// no `TypeTest` says so, so a pattern match cannot recover them: these two casts are the only
// way across, and are kept here, out of the reach of the `cast` rule (see
// `.pyrocosm/flare/config.tel`). Only `Inspection`'s walker, whose quotes are the compiler's,
// calls them.
object Reflection:
  def typeRepr(using quotes: Quotes)(tpe: Types.Type): quotes.reflect.TypeRepr =
    tpe.asInstanceOf[quotes.reflect.TypeRepr]

  def symbol(using quotes: Quotes)(symbol: Symbols.Symbol): quotes.reflect.Symbol =
    symbol.asInstanceOf[quotes.reflect.Symbol]
