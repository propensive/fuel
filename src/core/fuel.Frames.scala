package fuel

import soundness.*

import dysasymptotics.linearSize

object Frames:
  // What a frame shows of an error: the paragraph of the compiler's message which says what
  // is wrong, on one line. That is the library's own message where the compiler quotes one
  // (it begins with a bolt code), and otherwise the message's opening lines, before the
  // compiler turns to what it tried and what might be imported.
  def caption(message: Text): Text =
    val lines: List[Text] = message.trim.cut(t"\n").map(_.trim)

    val own: Optional[Ordinal] = lines.where(_.starts(t"[↯/"))
    val from: List[Text] = own.lay(lines) { (index: Ordinal) => lines.skip(index.n0) }
    val end: Optional[Ordinal] = from.where { (line: Text) => line == t"" || line.ends(t":") }
    val paragraph: List[Text] = end.lay(from) { (index: Ordinal) => from.keep(index.n0) }

    if paragraph.nil then from.head.or(t"") else paragraph.join(t" ")
