package fuel

import soundness.*

// A range of a fragment's text named by its first and last few characters — `Mi..es` for a
// run beginning `Mi` and ending `es` — or by a literal run of text, as Amok named them: short
// enough to write in a preamble, stable under edits elsewhere in the fragment.
object Selection:
  def parse(text: Text): Selection =
    val parts: List[Text] = text.cut(t"..")

    parts match
      case start :: end :: _ => Selection(start, end)
      case _                 => Selection(text, Unset)

case class Selection(start: Text, end: Optional[Text]):
  // The offsets of the first match: where `start` first occurs, to the end of the first `end`
  // after it; or the literal alone.
  def findIn(code: Text): Optional[(Int, Int)] =
    val from: Int = code.s.indexOf(start.s)

    if from < 0 then Unset else end match
      case end: Text =>
        val to: Int = code.s.indexOf(end.s, from + start.length)
        if to < 0 then Unset else (from, to + end.length)

      case _ =>
        (from, from + start.length)
